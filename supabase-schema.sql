-- 1. ตาราง Users (ข้อมูลผู้เล่น และเบอร์พร้อมเพย์)
CREATE TABLE IF NOT EXISTS users (
  id TEXT PRIMARY KEY,
  username TEXT NOT NULL,
  display_name TEXT,
  promptpay TEXT,
  created_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
);

-- 2. ตาราง Sessions (รอบโต๊ะ Poker)
CREATE TABLE IF NOT EXISTS sessions (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  guild_id TEXT NOT NULL,
  channel_id TEXT NOT NULL,
  host_id TEXT NOT NULL,
  default_buyin NUMERIC NOT NULL,
  status TEXT NOT NULL DEFAULT 'active', -- 'active' | 'completed' | 'cancelled'
  message_id TEXT,
  created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
  ended_at TIMESTAMPTZ
);

-- 3. ตาราง Session Players (ผู้เล่นในแต่ละโต๊ะ และยอดเงิน)
CREATE TABLE IF NOT EXISTS session_players (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  session_id BIGINT NOT NULL REFERENCES sessions(id) ON DELETE CASCADE,
  user_id TEXT NOT NULL,
  buy_in NUMERIC NOT NULL,
  cash_out NUMERIC,
  status TEXT NOT NULL DEFAULT 'playing', -- 'playing' | 'left'
  left_at TIMESTAMPTZ,
  created_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
);

-- 4. ตาราง Settlements (ประวัติรายการโอนเงินเคลียร์หนี้)
CREATE TABLE IF NOT EXISTS settlements (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  session_id BIGINT NOT NULL REFERENCES sessions(id) ON DELETE CASCADE,
  from_user_id TEXT NOT NULL,
  to_user_id TEXT NOT NULL,
  amount NUMERIC NOT NULL,
  created_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
);

-- สร้าง Indexes เพื่อให้ค้นหาข้อมูลและโหลดตาราง Leaderboard ได้เร็วสูงสุด
CREATE INDEX IF NOT EXISTS idx_sessions_guild_status ON sessions(guild_id, status);
CREATE INDEX IF NOT EXISTS idx_sessions_channel_status ON sessions(channel_id, status);
CREATE INDEX IF NOT EXISTS idx_session_players_session ON session_players(session_id);
CREATE INDEX IF NOT EXISTS idx_session_players_user ON session_players(user_id);
CREATE INDEX IF NOT EXISTS idx_settlements_session ON settlements(session_id);

-- ปิด Row Level Security (RLS) เพื่อให้ Discord Bot อ่านและเขียนข้อมูลได้ 100%
ALTER TABLE users DISABLE ROW LEVEL SECURITY;
ALTER TABLE sessions DISABLE ROW LEVEL SECURITY;
ALTER TABLE session_players DISABLE ROW LEVEL SECURITY;
ALTER TABLE settlements DISABLE ROW LEVEL SECURITY;

-- ยืนยันการสร้างเสร็จสมบูรณ์
COMMENT ON TABLE users IS 'Poker Bot Users & PromptPay';
COMMENT ON TABLE sessions IS 'Poker Game Sessions';
COMMENT ON TABLE session_players IS 'Poker Session Player Records';
COMMENT ON TABLE settlements IS 'Poker Settlement Debt Clearances';
